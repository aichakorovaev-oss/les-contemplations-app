export function getLocalizedCatalogue(lang: Lang): Painting[] {
  return RAW_CATALOGUE.map(item => {
    if (lang === 'en' && CATALOGUE_EN[item.id]) {
      const en = CATALOGUE_EN[item.id];
      return {
        ...item,
        title: en.title ?? item.title,
        medium: en.medium ?? item.medium,
        location: en.location ?? item.location,
        desc: en.desc ?? item.desc,
        artist: en.artist ?? item.artist,
      };
    }
    return { ...item };
  });
}

export function assignSlots(selectedPaintings: Painting[]): Painting[] {
  const slotsByRoom: Record<RoomKey, number[]> = { peach: [], blue: [], green: [], yellow: [] };
  WALL_SLOTS.forEach((s, i) => {
    slotsByRoom[s.room].push(i);
  });
  const used = new Array(WALL_SLOTS.length).fill(false);

  const takeInRoom = (room: RoomKey) => {
    for (const i of (slotsByRoom[room] || [])) {
      if (!used[i]) {
        used[i] = true;
        return i;
      }
    }
    return -1;
  };

  const takeAny = () => {
    for (let i = 0; i < WALL_SLOTS.length; i++) {
      if (!used[i]) {
        used[i] = true;
        return i;
      }
    }
    return -1;
  };

  const MAX_W = 1.7, MAX_H = 2.0;

  return selectedPaintings.map(p => {
    const pref = p.room_hint || p.room || 'peach';
    let si = takeInRoom(pref);
    if (si < 0) si = takeAny();
    const slot = (si >= 0) ? WALL_SLOTS[si] : WALL_SLOTS[0];

    let w = typeof p.width === 'number' ? p.width : 1.4;
    let h = typeof p.height === 'number' ? p.height : 1.2;
    if (w > MAX_W) { h *= MAX_W / w; w = MAX_W; }
    if (h > MAX_H) { w *= MAX_H / h; h = MAX_H; }

    return {
      ...p,
      room: slot.room,
      room_hint: slot.room,
      wall: slot.wall,
      pos: slot.pos,
      width: w,
      height: h,
    };
  });
}
